/**
 * This script makes `src/azure-sizes-data.ts` from the size pages of the Azure documentation at one commit. It reads
 * the tree of the repository, each size page and each include file that a page names. Each request goes through the
 * polite send of `polite-crawler`, with one request each second for each host.
 *
 * Start: `node scripts/azure-sizes.ts [commit]` in the package folder. Without a commit, the script reads the head of `main`.
 */
import { writeFileSync } from "node:fs";
import { posix } from "node:path";
import { HostScheduler, realClock } from "polite-crawler/politeness";
import { parseAzureSizeTables, type AzureVmSize, type AzureVmSizesSource } from "../src/azure-sizes.ts";
import { readJson, redact, send, type Transport } from "../src/client.ts";

const REPOSITORY = "MicrosoftDocs/azure-compute-docs";
const FOLDER = "articles/virtual-machines/sizes";
const PAGE = /^articles\/virtual-machines\/sizes\/.+\.md$/;
const USER_AGENT = "market-sources";

const transport: Transport<AbortSignal> = async (exchange, signal) => {
  const init: RequestInit = { method: exchange.method, headers: { ...exchange.headers, "user-agent": USER_AGENT }, body: exchange.body, redirect: "manual" };
  const answer = await fetch(exchange.url, signal === undefined ? init : { ...init, signal });
  return { status: answer.status, statusText: answer.statusText, headers: Object.fromEntries(answer.headers), body: await answer.text() };
};
const pace = { scheduler: new HostScheduler(realClock, 2), now: realClock.now };

/** This function tries a send up to 3 times, 5 seconds apart, because a request with no answer can pass on the next try. */
async function retried<T>(task: () => Promise<T>): Promise<T> {
  for (let attempt = 1; ; attempt += 1) {
    try {
      return await task();
    } catch (error) {
      if (attempt === 3) throw error;
      await new Promise((resolve) => setTimeout(resolve, 5000));
    }
  }
}

async function get(url: string, what: string): Promise<string> {
  const host = new URL(url).host;
  const input = { source: host, host, minIntervalMs: 1000, what, secrets: [], redact, exchange: { method: "GET" as const, url, headers: {}, body: null } };
  const answer = await retried(() => send(pace, transport, input, undefined));
  if (answer.reply.status !== 200) throw new Error(`${host} answered ${answer.reply.status} to ${what}.`);
  return answer.reply.body;
}

async function json(url: string, what: string): Promise<unknown> {
  const host = new URL(url).host;
  const input = { source: host, host, minIntervalMs: 1000, what, secrets: [], redact, exchange: { method: "GET" as const, url, headers: { accept: "application/vnd.github+json" }, body: null } };
  const read = readJson(await retried(() => send(pace, transport, input, undefined)), input);
  if (!read.ok) throw new Error(read.problems.join(" "));
  return read.json;
}

const commit = process.argv[2] ?? ((await json(`https://api.github.com/repos/${REPOSITORY}/commits/main`, "the head of main")) as { sha: string }).sha;
const tree = (await json(`https://api.github.com/repos/${REPOSITORY}/git/trees/${commit}?recursive=1`, "the tree")) as { tree: { path: string; type: string }[]; truncated: boolean };
if (tree.truncated) throw new Error("The tree of the repository is truncated.");
const pages = tree.tree.filter((entry) => entry.type === "blob" && PAGE.test(entry.path)).map((entry) => entry.path);

const sizes = new Map<string, AzureVmSize>();
const notes: string[] = [];
const done = new Set<string>();
const queue = [...pages];
while (queue.length > 0) {
  const path = queue.shift() ?? "";
  if (done.has(path)) continue;
  done.add(path);
  const read = parseAzureSizeTables(await get(`https://raw.githubusercontent.com/${REPOSITORY}/${commit}/${path}`, path));
  for (const note of read.notes) notes.push(`${path}: ${note}`);
  for (const include of read.includes) queue.push(posix.normalize(posix.join(posix.dirname(path), include)));
  for (const size of read.sizes) {
    const known = sizes.get(size.sku);
    if (known !== undefined && (known.vcpu !== size.vcpu || known.memoryGiB !== size.memoryGiB)) notes.push(`${path}: ${size.sku} has two sizes.`);
    sizes.set(size.sku, size);
  }
}

const source: AzureVmSizesSource = {
  repository: REPOSITORY,
  commit,
  path: FOLDER,
  license: "CC-BY-4.0",
  licenseUrl: "https://creativecommons.org/licenses/by/4.0/",
  read: new Date().toISOString().slice(0, 10),
  attribution: `The vCPUs and the memory of each size come from the size tables of the Azure documentation, Microsoft, ${REPOSITORY} at the commit ${commit.slice(0, 12)}, under CC BY 4.0. The script keeps only these two columns.`,
};
const rows = [...sizes.values()].sort((a, b) => a.sku.localeCompare(b.sku, "en"));
const text = [
  "// This file is generated by `scripts/azure-sizes.ts`. Do not edit it.",
  `// ${source.attribution}`,
  'import type { AzureVmSizesSource } from "./azure-sizes.ts";',
  "",
  "/** The source of `AZURE_VM_SIZE_TABLE`, with its license and its attribution. */",
  `export const AZURE_VM_SIZES_SOURCE: AzureVmSizesSource = ${JSON.stringify(source, null, 2)};`,
  "",
  "/** The count of vCPUs and the memory in GiB of each size, by its ARM SKU name. */",
  "export const AZURE_VM_SIZE_TABLE: Readonly<Record<string, readonly [vcpu: number, memoryGiB: number]>> = {",
  ...rows.map((size) => `  ${JSON.stringify(size.sku)}: [${size.vcpu}, ${size.memoryGiB}],`),
  "};",
  "",
].join("\n");
writeFileSync(new URL("../src/azure-sizes-data.ts", import.meta.url), text);
console.log(JSON.stringify({ commit: commit.slice(0, 12), pages: pages.length, files: done.size, sizes: rows.length, notes: notes.length }));
for (const note of notes.slice(0, 40)) console.log(note);
